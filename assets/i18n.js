window.currentLang = 'en';

window.setLang = function(lang){
  const dict = window.I18N[lang] || window.I18N.en;
  window.currentLang = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el=>{
    const key = el.getAttribute('data-i18n-ph');
    if(dict[key] !== undefined) el.setAttribute('placeholder', dict[key]);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el=>{
    const key = el.getAttribute('data-i18n-aria');
    if(dict[key] !== undefined) el.setAttribute('aria-label', dict[key]);
  });
  const en = document.getElementById('btn-en');
  const ar = document.getElementById('btn-ar');
  if(en) en.setAttribute('aria-pressed', String(lang==='en'));
  if(ar) ar.setAttribute('aria-pressed', String(lang==='ar'));
  try{ localStorage.setItem('bineisa-lang', lang); }catch(e){}
  document.dispatchEvent(new CustomEvent('bineisa:langchange',{detail:{lang}}));
};

window.t = function(key, vars){
  const dict = window.I18N[window.currentLang] || window.I18N.en;
  let s = dict[key] !== undefined ? dict[key] : key;
  if(vars) Object.keys(vars).forEach(k=>{ s = s.replace('{'+k+'}', vars[k]); });
  return s;
};

window.initLang = function(){
  let lang = 'en';
  try{ lang = localStorage.getItem('bineisa-lang') || 'en'; }catch(e){}
  if(lang !== 'en') window.setLang(lang);
};
